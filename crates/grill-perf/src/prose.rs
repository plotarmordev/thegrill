/// Appends exactly `characters` ASCII bytes of prose determined by `text_salt`.
pub(crate) fn v1(output: &mut String, characters: usize, text_salt: &str) {
    use sha2::{Digest, Sha256};
    let mut hash = Sha256::new();
    hash.update(b"grill-perf/generated-prose-v1\0");
    hash.update(text_salt.as_bytes());
    let digest = hash.finalize();
    let mut state = u64::from_le_bytes(digest[..8].try_into().unwrap());
    let end = output.len() + characters;
    let mut words_left = 0;
    while output.len() < end {
        let first = words_left == 0;
        if first {
            words_left = 6 + next(&mut state) % 11;
        }
        let word = WORDS_V1[(next(&mut state) % WORDS_V1.len() as u64) as usize];
        let count = word.len().min(end - output.len());
        if first {
            output.push(char::from(word.as_bytes()[0].to_ascii_uppercase()));
            output.push_str(&word[1..count]);
        } else {
            output.push_str(&word[..count]);
        }
        words_left -= 1;
        if words_left == 0 && output.len() < end {
            output.push('.');
        }
        if output.len() < end {
            output.push(' ');
        }
    }
}

fn next(state: &mut u64) -> u64 {
    // SplitMix64's wrapping arithmetic fixes the stream across architectures.
    *state = state.wrapping_add(0x9e3779b97f4a7c15);
    let mut value = *state;
    value = (value ^ (value >> 30)).wrapping_mul(0xbf58476d1ce4e5b9);
    value = (value ^ (value >> 27)).wrapping_mul(0x94d049bb133111eb);
    value ^ (value >> 31)
}
